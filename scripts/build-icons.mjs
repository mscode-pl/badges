const bySlug = new Map(Object.values(simpleIcons).filter((i) => i?.slug).map((i) => [i.slug, i]));
const missing = Object.entries(selection).filter(([, slug]) => !bySlug.has(slug));
if (missing.length) {
    console.error('not in simple-icons:', missing.map(([id, slug]) => `${id} (${slug})`).join(', '));
    process.exit(1);
}

const entries = Object.entries(selection)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, slug]) => {
        const icon = bySlug.get(slug);
        return `    ${JSON.stringify(id)}: { title: ${JSON.stringify(icon.title)}, hex: '#${icon.hex.toLowerCase()}', path: ${JSON.stringify(icon.path)} },`;
    });

const out = `// Generated by scripts/build-icons.mjs from simple-icons (CC0). Do not edit by hand.
import type { PathIcon } from './types';

export const simpleIcons: Record<string, PathIcon> = {
${entries.join('\n')}
};
`;
fs.writeFileSync(new URL('../src/icons/simple.generated.ts', import.meta.url), out);
